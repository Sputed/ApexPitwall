import { DriverTelemetryTrace, DriverTiming, TelemetryPoint } from '../types/f1';

// Generate realistic Baku lap telemetry for a driver with authentic telemetry profile
export function generateLapTelemetry(
  driverCode: string,
  driverName: string,
  teamColor: string,
  baseLapSeconds: number,
  deltaOffsetMs: number
): DriverTelemetryTrace {
  const totalDistance = 6003; // Baku City Circuit length in meters
  const sampleSteps = 120;
  const points: TelemetryPoint[] = [];

  let cumTime = 0;
  for (let i = 0; i <= sampleSteps; i++) {
    const distance = (i / sampleSteps) * totalDistance;
    let speed = 250;
    let throttle = 100;
    let brake = 0;
    let gear = 7;
    let drs = false;

    if (distance < 850) {
      speed = 310 + (distance / 850) * 35;
      throttle = 100;
      gear = 8;
      drs = true;
    } else if (distance >= 850 && distance < 980) {
      const brakeProgress = (distance - 850) / 130;
      speed = Math.max(92, 345 - brakeProgress * 250);
      throttle = 0;
      brake = Math.min(100, Math.round(95 * (1 - brakeProgress * 0.4)));
      gear = 3;
    } else if (distance >= 980 && distance < 1450) {
      speed = 100 + ((distance - 980) / 470) * 160;
      throttle = 90;
      gear = 5;
    } else if (distance >= 1450 && distance < 1560) {
      speed = 105;
      throttle = 20;
      brake = 75;
      gear = 3;
    } else if (distance >= 1560 && distance < 2100) {
      speed = 110 + ((distance - 1560) / 540) * 200;
      throttle = 100;
      gear = 7;
      drs = true;
    } else if (distance >= 2100 && distance < 2250) {
      speed = 98;
      throttle = 10;
      brake = 85;
      gear = 3;
    } else if (distance >= 2250 && distance < 3100) {
      speed = 140 + Math.sin(distance / 120) * 45;
      throttle = 60 + Math.sin(distance / 100) * 35;
      gear = 4;
      brake = speed < 120 ? 40 : 0;
    } else if (distance >= 3100 && distance < 3400) {
      speed = 82 + ((distance - 3100) / 300) * 35;
      throttle = 45;
      gear = 2;
      brake = 15;
    } else if (distance >= 3400 && distance < 4100) {
      speed = 150 + ((distance - 3400) / 700) * 130;
      throttle = 85;
      gear = 6;
    } else if (distance >= 4100 && distance < 4250) {
      speed = 112;
      throttle = 0;
      brake = 80;
      gear = 3;
    } else {
      const straightProg = (distance - 4250) / (totalDistance - 4250);
      speed = Math.min(348, 120 + straightProg * 225);
      throttle = 100;
      brake = 0;
      gear = straightProg > 0.6 ? 8 : straightProg > 0.3 ? 7 : 5;
      drs = straightProg > 0.4;
    }

    const driverBias = (driverCode.charCodeAt(0) % 5) - 2;
    speed = Math.round(Math.max(60, speed + driverBias * 1.5 + Math.sin(i * 0.4) * 2));
    throttle = Math.min(100, Math.max(0, Math.round(throttle)));
    brake = Math.min(100, Math.max(0, Math.round(brake)));

    const rpm = Math.round(speed > 300 ? 11800 + Math.random() * 400 : 8500 + (speed % 50) * 70);
    const dt = totalDistance / sampleSteps / Math.max(25, speed * (1000 / 3600));
    cumTime += dt;

    points.push({
      distance: Math.round(distance),
      speed,
      throttle,
      brake,
      gear,
      rpm,
      drs,
      time: Number(cumTime.toFixed(3)),
    });
  }

  const factor = (baseLapSeconds + deltaOffsetMs / 1000) / cumTime;
  points.forEach((p) => {
    p.time = Number((p.time * factor).toFixed(3));
  });

  const minutes = Math.floor((baseLapSeconds + deltaOffsetMs / 1000) / 60);
  const seconds = ((baseLapSeconds + deltaOffsetMs / 1000) % 60).toFixed(3);
  const bestLapTime = `${minutes}:${Number(seconds) < 10 ? '0' : ''}${seconds}`;

  return {
    driverCode,
    driverName,
    teamColor,
    bestLapTime,
    points,
  };
}

